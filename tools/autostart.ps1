# autostart.ps1 - 把「摄像头浮窗（带看门狗）」装进 Windows 开机启动
#
#   .\tools\autostart.ps1            # 安装（当前用户，不需要管理员）
#   .\tools\autostart.ps1 -Remove    # 卸载
#   .\tools\autostart.ps1 -Status    # 看看现在装了没
param(
    [switch]$Remove,
    [switch]$Status,
    [int]$Size = 380
)

$ErrorActionPreference = "Continue"
$Root = Split-Path $PSScriptRoot -Parent
$startup = [Environment]::GetFolderPath("Startup")
$vbs = Join-Path $startup "cam-bubble.vbs"

if ($Status) {
    if (Test-Path $vbs) {
        Write-Host "已安装: $vbs" -ForegroundColor Green
        Get-Content $vbs
    } else {
        Write-Host "未安装（$vbs 不存在）" -ForegroundColor Yellow
    }
    return
}

if ($Remove) {
    if (Test-Path $vbs) { Remove-Item $vbs -Force; Write-Host "已移除开机启动: $vbs" -ForegroundColor Green }
    else { Write-Host "本来就没装" -ForegroundColor Yellow }
    return
}
$ps1 = $Root + '\wait_phone.ps1'
$text = @"
' cam-bubble autostart (generated by tools/autostart.ps1)
' waits 25s so the network / adb is ready after boot
Set sh = CreateObject("WScript.Shell")
WScript.Sleep 25000
sh.CurrentDirectory = "$Root"
sh.Run "powershell -NoProfile -ExecutionPolicy Bypass -WindowStyle Minimized -File ""$ps1"" -Minutes 30", 7, False
"@
[IO.File]::WriteAllText($vbs, $text, [Text.Encoding]::ASCII)
Write-Host "已安装开机启动: $vbs" -ForegroundColor Green
Get-Content $vbs | ForEach-Object { Write-Host "    $_" -ForegroundColor DarkGray }